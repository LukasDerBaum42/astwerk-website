//go:build ignore

// Command gencss writes style/code.css from chroma's own style definitions.
//
// The highlighter emits classes rather than inline styles, so the colours live in
// one stylesheet that both markdown code blocks and templ-embedded snippets
// share. Generating it keeps those colours honest: they come from the same
// chroma styles the formatter was configured with, rather than being copied by
// hand and slowly drifting.
//
//	go run tools/gencss/main.go > style/code.css
package main

import (
	"fmt"
	"log"
	"os"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

// The dark style must match templates.StyleName for consistency; the light
// style is chosen for hue separation — github's own light palette puts tags,
// strings and operators all in the same dark-blue family, which reads as
// "same colour" on a light background. pastie keeps every token family a
// distinct hue.
const (
	light = "pastie"
	dark  = "github-dark"
)

func main() {
	out := os.Stdout

	fmt.Fprintf(out, "/* Generated by tools/gencss. Do not edit by hand.\n"+
		"   Regenerate with: go run tools/gencss/main.go > style/code.css\n"+
		"   Dark (default, unscoped): %s. Light: %s.\n\n"+
		"   Scoped by [data-theme], not prefers-color-scheme: the site's light/dark\n"+
		"   toggle in style.css is a manual choice, not the OS preference, so code\n"+
		"   blocks have to follow that same signal or they show a mismatched palette\n"+
		"   the moment someone flips the toggle against their OS setting.\n\n"+
		"   The dark block stays unscoped and first, because the two chroma styles\n"+
		"   don't cover the same token classes: github styles .nx and .p (plain\n"+
		"   identifiers and punctuation — most of any Go snippet) as near-black, and\n"+
		"   github-dark has no rule for them at all. */\n\n", dark, light)

	darkCSS, err := styleCSS(dark)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(out, "/* %s (default) */\n%s\n", dark, indent(darkCSS))

	lightCSS, err := styleCSS(light)
	if err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(out, "\n/* %s */\n%s\n", light, indent(scope(lightCSS, `[data-theme="light"]`)))
	// Some light styles (pastie) define no PreWrapper foreground, so the unscoped
	// dark rule's near-white would leak into light mode — white code on a white
	// page. Pin a dark base foreground for the light block; the token rules on
	// top of it keep their own colours.
	fmt.Fprintf(out, "\n/* light base foreground */\n[data-theme=\"light\"] .chroma { color: #1f2328; }\n")
}

// scope prefixes every selector in css with prefix, so each rule applies only
// under that attribute instead of unconditionally.
//
// Each rule is one line ("/* Comment */ .chroma .err { ... }"), so this works
// line by line rather than with one regex over the whole file — a regex
// anchored on the trailing class before "{" would prefix only ".err" and leave
// ".chroma" outside the scope, breaking the descendant relationship between
// them.
func scope(css, prefix string) string {
	lines := strings.Split(css, "\n")
	for i, line := range lines {
		brace := strings.Index(line, "{")
		if brace < 0 {
			continue
		}
		head := line[:brace]

		lead := ""
		selector := head
		if end := strings.Index(head, "*/"); end >= 0 {
			lead, selector = head[:end+2]+" ", head[end+2:]
		}
		selector = strings.TrimSpace(selector)
		if selector == "" {
			continue
		}

		parts := strings.Split(selector, ",")
		for j, p := range parts {
			parts[j] = prefix + " " + strings.TrimSpace(p)
		}
		lines[i] = lead + strings.Join(parts, ", ") + " {" + line[brace+1:]
	}
	return strings.Join(lines, "\n")
}

func indent(css string) string {
	lines := strings.Split(strings.TrimRight(css, "\n"), "\n")
	for i, l := range lines {
		if l == "" {
			continue
		}
		lines[i] = "\t" + l
	}
	return strings.Join(lines, "\n")
}

func styleCSS(name string) (string, error) {
	style := styles.Get(name)
	if style == nil {
		return "", fmt.Errorf("unknown chroma style %q", name)
	}
	var sb strings.Builder
	f := chromahtml.New(chromahtml.WithClasses(true))
	if err := f.WriteCSS(&sb, style); err != nil {
		return "", err
	}
	return sb.String(), nil
}
